#!/usr/bin/env bash
# Generate per-kind UTF-8 Metal embeds for CGO (GGML_METAL_EMBED_LIBRARY).
#
# Mirrors ml/backend/ggml/ggml/src/ggml-metal/CMakeLists.txt embed rules:
# concatenate shared headers + kernels/<kind>.metal, strip internal includes,
# inline ggml-common.h + ggml-metal-impl.h, emit ggml-metal-embed.s .incbin
# symbols. Eliza TBQ/QJL/polar sources are copied as their own kinds when
# present under eliza-shipped/ (do not concat onto misc).
#
# Usage:
#   ./scripts/build/gen_ggml_metal_embed.sh
#   go generate ./ml/backend/ggml/ggml/src/ggml-metal/
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
METAL_DIR="${ROOT}/ml/backend/ggml/ggml/src/ggml-metal"
KERNELS="${METAL_DIR}/kernels"
COMMON_H="${METAL_DIR}/../ggml-common.h"
IMPL_H="${METAL_DIR}/ggml-metal-impl.h"
DEVICE_M="${METAL_DIR}/ggml-metal-device.m"
ASM_OUT="${METAL_DIR}/ggml-metal-embed.s"

if [[ ! -f "${DEVICE_M}" || ! -f "${COMMON_H}" || ! -f "${IMPL_H}" ]]; then
  echo "error: missing Metal sources under ${METAL_DIR}" >&2
  exit 1
fi

# Kinds from GGML_METAL_LIBS X(ENUM, name) — second field is basename / symbol stem.
# Bash 3.2 (macOS /bin/bash) has no mapfile.
KINDS=()
while IFS= read -r kind; do
  [[ -n "${kind}" ]] && KINDS+=("${kind}")
done < <(
  sed -n '/^#define GGML_METAL_LIBS/,/^[[:space:]]*$/p' "${DEVICE_M}" \
    | sed -n 's/.*X([^,]*,[[:space:]]*\([a-z0-9_]*\)).*/\1/p'
)

if [[ ${#KINDS[@]} -eq 0 ]]; then
  echo "error: no kinds parsed from GGML_METAL_LIBS in ${DEVICE_M}" >&2
  exit 1
fi

_inline_kernel() {
  local kind="$1"
  local src="$2"
  local embed="${METAL_DIR}/ggml-metal-embed-${kind}.metal"
  local tmp1 tmp2 tmp3
  tmp1="$(mktemp)"
  tmp2="$(mktemp)"
  tmp3="$(mktemp)"

  local headers=("${KERNELS}/common.h")
  if grep -q '#include "dequantize\.h"' "${src}"; then
    headers+=("${KERNELS}/dequantize.h")
  fi
  if grep -q '#include "quantize\.h"' "${src}"; then
    headers+=("${KERNELS}/quantize.h")
  fi
  if grep -q '#include "fa_common\.metal"' "${src}"; then
    headers+=("${KERNELS}/fa_common.metal")
  fi
  if grep -q '#include "fa_vec_common\.metal"' "${src}"; then
    headers+=("${KERNELS}/fa_vec_common.metal")
  fi

  cat "${headers[@]}" "${src}" > "${tmp1}"
  sed \
    -e '/#include "common.h"/d' \
    -e '/#include "dequantize.h"/d' \
    -e '/#include "quantize.h"/d' \
    -e '/#include "fa_common.metal"/d' \
    -e '/#include "fa_vec_common.metal"/d' \
    -e '/#pragma once/d' \
    < "${tmp1}" > "${tmp2}"
  sed -e "/__embed_ggml-common.h__/r ${COMMON_H}" -e "/__embed_ggml-common.h__/d" \
    < "${tmp2}" > "${tmp3}"
  sed -e "/#include \"ggml-metal-impl.h\"/r ${IMPL_H}" -e "/#include \"ggml-metal-impl.h\"/d" \
    < "${tmp3}" > "${embed}"

  rm -f "${tmp1}" "${tmp2}" "${tmp3}"
}

_emit_asm_chunk() {
  local kind="$1"
  local embed_name="ggml-metal-embed-${kind}.metal"
  printf '.globl _ggml_metallib_%s_start\n' "${kind}"
  printf '_ggml_metallib_%s_start:\n' "${kind}"
  printf '.incbin "%s"\n' "${embed_name}"
  printf '.globl _ggml_metallib_%s_end\n' "${kind}"
  printf '_ggml_metallib_%s_end:\n' "${kind}"
}

{
  echo '//go:build darwin && arm64'
  echo
  echo '// Code generated by scripts/build/gen_ggml_metal_embed.sh. DO NOT EDIT.'
  echo '.section __DATA,__ggml_metallib'
  for kind in "${KINDS[@]}"; do
    src="${KERNELS}/${kind}.metal"
    if [[ ! -f "${src}" ]]; then
      echo "error: missing ${src}" >&2
      exit 1
    fi
    _inline_kernel "${kind}" "${src}"
    _emit_asm_chunk "${kind}"
  done

  # Eliza TBQ/QJL/polar: only emit when listed in GGML_METAL_LIBS (device.m).
  # Concatenating onto misc redefines block_qjl1_256 and fails JIT — see
  # docs/apple-silicon-metal.md. Sources live in eliza-shipped/ for metallib builds.
  :
} > "${ASM_OUT}"

echo ">>> wrote ${ASM_OUT} (${#KINDS[@]} kernel kinds)" >&2
